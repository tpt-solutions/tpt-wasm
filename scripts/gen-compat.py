"""Generate docs/standards/compat.md from feature-registry.toml.

The registry is the source of truth; the compatibility page is derived from it and
is never edited by hand. Two checks run before anything is written:

* every proposal in [features] has an [evidence.<name>] row, and no row is orphaned;
* no proposal is marked false while some piece of its evidence is not false, since
  evidence for a feature that is not implemented means the registry is wrong.

Usage:
    python3 scripts/gen-compat.py           write docs/standards/compat.md
    python3 scripts/gen-compat.py --check   exit 1 if the page is out of date or the
                                            registry is inconsistent (used in CI)
"""

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "feature-registry.toml"
OUTPUT = ROOT / "docs" / "standards" / "compat.md"
EVIDENCE_KEYS = ("tested", "fuzzed", "differential", "verified")
MARK = {True: "yes", "partial": "partial", False: "no"}


def load():
    with REGISTRY.open("rb") as handle:
        return tomllib.load(handle)


def problems(registry):
    features = registry.get("features", {})
    evidence = registry.get("evidence", {})
    found = []
    proposals = [name for name in features if name not in ("status",)]
    for name in proposals:
        if name not in evidence:
            found.append(f"proposal '{name}' has no [evidence.{name}] row")
    for name in evidence:
        if name not in proposals:
            found.append(f"[evidence.{name}] has no matching proposal in [features]")
    for name in proposals:
        row = evidence.get(name, {})
        for key in EVIDENCE_KEYS:
            if key not in row:
                found.append(f"[evidence.{name}] is missing '{key}'")
        claimed = [key for key in EVIDENCE_KEYS if row.get(key, False) is not False]
        status = features.get(name, False)
        if claimed and status is False:
            found.append(
                f"'{name}' is not implemented but has evidence ({', '.join(claimed)})"
            )
        if claimed and not row.get("notes"):
            found.append(f"[evidence.{name}] claims {', '.join(claimed)} without notes")
    return found


def render(registry):
    features = registry["features"]
    evidence = registry["evidence"]
    lines = [
        "# Compatibility",
        "",
        "<!-- Generated by scripts/gen-compat.py from feature-registry.toml. Do not edit. -->",
        "",
        "Which WebAssembly proposals TPT-Wasm implements, and what evidence stands behind",
        "each one. The registry is the source; this page is derived from it.",
        "",
        "A **status** of `yes` means the proposal is implemented. `partial` means part of it",
        "is. The four evidence columns say what is checked, not what is implemented:",
        "",
        "- **tested**: unit, integration, or spec-suite tests run in CI.",
        "- **fuzzed**: a fuzz target or a seeded generator covers it.",
        "- **differential**: compared against Micro, the golden result.",
        "- **verified**: a Lean proof or a checked invariant in `formal/`.",
        "",
        "| Proposal | Status | Tested | Fuzzed | Differential | Verified |",
        "|---|---|---|---|---|---|",
    ]
    for name in features:
        if name == "status":
            continue
        status = MARK[features[name]]
        row = evidence[name]
        cells = [MARK[row[key]] for key in EVIDENCE_KEYS]
        lines.append(f"| `{name}` | {status} | " + " | ".join(cells) + " |")
    lines += ["", "## Notes", ""]
    for name in features:
        if name == "status":
            continue
        notes = evidence[name].get("notes")
        if notes:
            lines.append(f"- **`{name}`**: {notes}")
    lines += [
        "",
        "## MVP status ladder",
        "",
        "| Rung | State |",
        "|---|---|",
    ]
    for rung, state in registry["features"]["status"].items():
        lines.append(f"| `{rung}` | {MARK.get(state, state)} |")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    registry = load()
    found = problems(registry)
    if found:
        for finding in found:
            print(f"feature-registry: {finding}", file=sys.stderr)
        return 1
    text = render(registry)
    if "--check" in argv:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(ROOT)} is out of date; run scripts/gen-compat.py",
                file=sys.stderr,
            )
            return 1
        print("compat page is up to date")
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
